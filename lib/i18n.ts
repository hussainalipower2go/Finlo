export function isRTL(lang: LangCode | string): boolean {
  const l = LANGUAGES.find((x) => x.code === lang);
  return !!l?.rtl;
}

export function getStoredLanguage(): LangCode {
  if (typeof window === "undefined") return DEFAULT_LANG;
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && LANGUAGES.some((x) => x.code === stored)) return stored as LangCode;
  } catch {}
  return DEFAULT_LANG;
}

export function storeLanguage(lang: LangCode): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {}
}

